/**
 * Copy i18n/region-defaults/*.json into the extension module the service worker can import.
 * Usage: node scripts/sync-region-defaults.mjs [--check]
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = 'i18n/region-defaults';
const files = readdirSync(dir).filter((name) => name.endsWith('.json')).sort();
const entries = files.map((name) => {
  const id = name.slice(0, -'.json'.length);
  const data = JSON.parse(readFileSync(`${dir}/${name}`, 'utf8'));
  return `  ${id}: ${JSON.stringify(data)}`;
});

const outputPath = 'extension/src/config/region-defaults-data.js';
const output = `/**
 * Packaged copy of i18n/region-defaults/*.json.
 * Generated by scripts/sync-region-defaults.mjs.
 * The service worker imports this module. It cannot import those JSON files:
 * they live outside the extension root, and extension workers reject JSON imports.
 */

export const regionDefaultFiles = {
${entries.join(',\n')}
};
`;

if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = readFileSync(outputPath, 'utf8');
  } catch {
    // The error below explains how to create the missing file.
  }
  if (existing !== output) {
    console.error(
      'extension/src/config/region-defaults-data.js is stale; run node scripts/sync-region-defaults.mjs'
    );
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${outputPath} (${files.length} locales)`);
}
