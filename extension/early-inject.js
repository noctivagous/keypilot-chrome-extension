      if (!Object.prototype.hasOwnProperty.call(changes, KEYBOARD_HELP_STORAGE_KEY)) return;
      const next = Boolean(changes[KEYBOARD_HELP_STORAGE_KEY]?.newValue);
      applyEarlyKeyboardHelpVisibility(next);
